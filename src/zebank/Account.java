    private void saveCustomer() {
        String Balance = txtbalance.getText().trim();

    if (Balance.isEmpty()) {
        //JOptionPane.showMessageDialog(this, "Please enter a valid balance.");
        return;
    }

    try {
        Double.parseDouble(Balance); // check if it's a valid number
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Balance must be a number.");
        return;
    }
        
        
    String Account_No = jLabel9.getText(); 
    String Customer_Id = txtcust_id.getText().trim(); 
    String Customer_Name = txtname.getText().trim(); 
    String Account_type = txtaccount.getSelectedItem().toString(); 
   

    try {
        Class.forName("com.mysql.cj.jdbc.Driver");
        con = DriverManager.getConnection("jdbc:mysql://localhost/zebank", "root", "");

        insert = con.prepareStatement("INSERT INTO account(acc_id, cust_id,cust_name, account_type, balance) VALUES (?, ?, ?, ?,?)");
        insert.setString(1, Account_No);   // should be Account_No
           insert.setString(2, Customer_Id);       // Error: 'cust_id' not defined
           insert.setString(3, Customer_Name);     // Error: 'cust_name' not defined
          insert.setString(4, Account_type);  // Error: 'account_type' not defined
            insert.setString(5, Balance); 

        int rows = insert.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this, "Account created successfully!");
            autoID(); // Reset form with new ID
            txtcust_id.setText("");
            txtname.setText("");
            txtbalance.setText("");
            txtaccount.setSelectedIndex(0);
        } else {
            JOptionPane.showMessageDialog(this, "Account creation failed.");
        }

    } catch (ClassNotFoundException | SQLException ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
    }
}
    
    

    
