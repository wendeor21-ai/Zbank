    private void autoID() {
    try {
        Class.forName("com.mysql.cj.jdbc.Driver");
        con = DriverManager.getConnection("jdbc:mysql://localhost/zebank", "root", "");

        Statement s = con.createStatement();
        ResultSet rs = s.executeQuery("SELECT MAX(acc_id) FROM account");

        if (rs.next()) {
            String maxId = rs.getString(1);

            if (maxId == null || maxId.length() < 3 || !maxId.startsWith("AC")) {
                jLabel9.setText("AC001");  // fallback to initial value
            } else {
                String prefix = maxId.substring(0, 2);
                String numPart = maxId.substring(2);

                try {
                    int id = Integer.parseInt(numPart);
                    id++;
                    jLabel9.setText(prefix + String.format("%03d", id));
                } catch (NumberFormatException e) {
                    jLabel9.setText("AC001"); // fallback if numeric part is not a number
                }
            }
        } else {
            jLabel9.setText("AC001");
        }

    } catch (ClassNotFoundException | SQLException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
    }
}

