    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
   
        
    String fromaccount = txtfacc.getText().trim();
    String balanceStr = txtbalance.getText().trim();
    String toaccount = txttoaccount.getText().trim();
    String amountStr = txtamount.getText().trim();

    if (fromaccount.isEmpty() || toaccount.isEmpty() || amountStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all fields.");
        return;
    }

    try {
        double currentBalance = Double.parseDouble(balanceStr);
        double transferAmount = Double.parseDouble(amountStr);

        if (transferAmount <= 0 || transferAmount > currentBalance) {
            JOptionPane.showMessageDialog(this, "Invalid transfer amount.");
            return;
        }

        Class.forName("com.mysql.cj.jdbc.Driver");
        con = DriverManager.getConnection("jdbc:mysql://localhost/zebank", "root", "");
        con.setAutoCommit(false); // 🔧 CORRECT WAY

        // Deduct from sender
        st1 = con.prepareStatement("UPDATE account SET balance = balance - ? WHERE acc_id = ?");
        st1.setDouble(1, transferAmount);
        st1.setString(2, fromaccount);
        st1.executeUpdate();

        // Add to recipient
        st2 = con.prepareStatement("UPDATE account SET balance = balance + ? WHERE acc_id = ?");
        st2.setDouble(1, transferAmount);
        st2.setString(2, toaccount);
        st2.executeUpdate();

        // Log the transfer
        st3 = con.prepareStatement("INSERT INTO transfer(from_account, to_account, amount) VALUES (?, ?, ?)");
        st3.setString(1, fromaccount);
        st3.setString(2, toaccount);
        st3.setDouble(3, transferAmount);
        st3.executeUpdate();

        con.commit(); // ✅ All good, commit
        JOptionPane.showMessageDialog(this, "Transfer successful!");

            
       } catch (Exception ex) {
        try {
            if (con != null) {
                con.rollback(); // 🔁 Rollback if error occurs
            }
        } catch (SQLException rollbackEx) {
            Logger.getLogger(Transfer.class.getName()).log(Level.SEVERE, null, rollbackEx);
        }
        Logger.getLogger(Transfer.class.getName()).log(Level.SEVERE, null, ex);
        JOptionPane.showMessageDialog(this, "Transfer failed. Please check details.");
    } finally {
        try {
            if (con != null) con.setAutoCommit(true); // restore auto-commit
            if (st1 != null) st1.close();
            if (st2 != null) st2.close();
            if (st3 != null) st3.close();
            if (con != null) con.close();
        } catch (SQLException cleanupEx) {
            Logger.getLogger(Transfer.class.getName()).log(Level.SEVERE, null, cleanupEx);
        }
    }
        
    }//GEN-LAST:event_jButton2ActionPerformed

