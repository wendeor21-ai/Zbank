    private boolean isValidEthiopianPhone(String phone) {
        if (phone == null || phone.trim().isEmpty()) return false;
        String cleanedPhone = phone.trim();
        if (!ETHIOPIAN_PHONE_PATTERN.matcher(cleanedPhone).matches()) return false;

        // Check operator digit
        if (cleanedPhone.startsWith("+251")) {
            String operatorDigit = cleanedPhone.substring(4, 5);
            return operatorDigit.equals("9") || operatorDigit.equals("7");
        } else if (cleanedPhone.startsWith("0")) {
            String operatorDigit = cleanedPhone.substring(1, 2);
            return operatorDigit.equals("9") || operatorDigit.equals("7");
        }
        return false;
    }
    
    private void autoID() {
    try {
        Class.forName("com.mysql.cj.jdbc.Driver");
        con = DriverManager.getConnection("jdbc:mysql://localhost/zebank", "root", "");

        Statement s = con.createStatement();
        ResultSet rs = s.executeQuery("SELECT MAX(cust_id) FROM customer");

        if (rs.next()) {
            String maxId = rs.getString(1);

            if (maxId == null || maxId.length() < 3 || !maxId.startsWith("CS")) {
                jLabel9.setText("CS001");  // fallback to initial value
            } else {
                String prefix = maxId.substring(0, 2);
                String numPart = maxId.substring(2);

                try {
                    int id = Integer.parseInt(numPart);
                    id++;
                    jLabel9.setText(prefix + String.format("%03d", id));
                } catch (NumberFormatException e) {
                    jLabel9.setText("CS001"); // fallback if numeric part is not a number
                }
            }
        } else {
            jLabel9.setText("CS001");
        }

    } catch (ClassNotFoundException | SQLException e) {
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
    }
}

