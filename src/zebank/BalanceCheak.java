    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
         try {
        String accno = txtacc.getText().trim(); // remove extra spaces
        con = DriverManager.getConnection("jdbc:mysql://localhost/zebank", "root", "");
        pst = con.prepareStatement("SELECT balance FROM account WHERE acc_id = ?");
        pst.setString(1, accno);
        rs = pst.executeQuery();

        if (rs.next()) {
            double balance = rs.getDouble("balance");
            txtbalance.setText(String.valueOf(balance));
        } else {
            txtbalance.setText("Account not found.");
        }

        rs.close();
        pst.close();
        con.close();
             
             
         } catch (Exception ex) {
            txtbalance.setText("Error: " + ex.getMessage());
         }
    }//GEN-LAST:event_jButton1ActionPerformed

